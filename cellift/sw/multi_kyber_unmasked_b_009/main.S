    la sp, _stack_top

    /*
     * crypto_kem_dec(ss, ct, sk)
     *   a0 = ss  (32-byte shared secret output buffer)
     *   a1 = ct  (768-byte ciphertext — patched per trace)
     *   a2 = sk  (TAINTED — the secret key, 1632 bytes)
